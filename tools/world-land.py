"""Rasterise Natural Earth land into a 1-degree mask for the whereami globe.

Usage:
  curl -sfo land-50m.json https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-50m.json
  python3 tools/world-land.py land-50m.json src/lib/now/land.ts

The mask is 360 x 180 cells, row 0 at 90N, column 0 at 180W, one bit per
cell (1 = land), packed eight cells to a byte and written as base64.
"""
import base64
import json
import sys

src, out = sys.argv[1], sys.argv[2]
W, H = 360, 180

d = json.load(open(src))
sx, sy = d["transform"]["scale"]
tx, ty = d["transform"]["translate"]
arcs = []
for arc in d["arcs"]:
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx
        y += dy
        pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)


def ring(idx):
    pts = []
    for i in idx:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts


def unwrap(r):
    """Make longitudes continuous. A ring that goes all the way round
    (Antarctica) is closed through the south pole."""
    out = [r[0]]
    shift = 0
    for i in range(1, len(r)):
        dx = r[i][0] - r[i - 1][0]
        if dx > 180:
            shift -= 360
        elif dx < -180:
            shift += 360
        out.append((r[i][0] + shift, r[i][1]))
    if shift != 0:
        out.append((out[-1][0], -90.0))
        out.append((out[0][0], -90.0))
    return out


polys = []
for geom in d["objects"]["land"]["geometries"]:
    parts = [geom["arcs"]] if geom["type"] == "Polygon" else geom["arcs"]
    for part in parts:
        polys.append([unwrap(ring(r)) for r in part])

bits = [[False] * W for _ in range(H)]
for row in range(H):
    lat = 90 - (row + 0.5) * 180 / H
    for poly in polys:
        xs = []
        for r in poly:
            n = len(r)
            for i in range(n):
                (x1, y1), (x2, y2) = r[i], r[(i + 1) % n]
                if (y1 > lat) != (y2 > lat):
                    xs.append(x1 + (lat - y1) * (x2 - x1) / (y2 - y1))
        xs.sort()
        # Even-odd: fill between each pair of crossings.
        for a, b in zip(xs[0::2], xs[1::2]):
            first = int((a + 180) // 1 + (1 if (a + 180) % 1 > 0.5 else 0))
            last = int((b + 180) // 1 + (1 if (b + 180) % 1 > 0.5 else 0))
            for col in range(first, last):
                bits[row][col % W] = True

packed = bytearray()
for row in bits:
    for start in range(0, W, 8):
        value = 0
        for k in range(8):
            if row[start + k]:
                value |= 1 << (7 - k)
        packed.append(value)

data = base64.b64encode(bytes(packed)).decode()
lines = [data[i : i + 76] for i in range(0, len(data), 76)]
with open(out, "w") as f:
    f.write(
        "// Generated by tools/world-land.py from Natural Earth land\n"
        "// (world-atlas@2.0.2, public domain). Do not edit by hand.\n"
        "// 360 x 180 cells of one degree, row 0 at 90N, column 0 at 180W, one bit\n"
        "// per cell (1 = land), eight cells to a byte, base64.\n"
        f"export const LAND_WIDTH = {W};\n"
        f"export const LAND_HEIGHT = {H};\n"
        "export const LAND = [\n"
        + "".join(f'  "{line}",\n' for line in lines)
        + '].join("");\n'
    )
print("land cells:", sum(map(sum, bits)), "of", W * H)
